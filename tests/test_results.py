ROOT = Path(__file__).resolve().parent.parent
GENERATED = ROOT / "oscal" / "generated" / "ve07-assessment-results.json"
GOLDEN = ROOT / "oscal" / "handwritten" / "ve07-assessment-results.json"
PLAN = ROOT / "oscal" / "handwritten" / "ve07-assessment-plan.json"
FAILING = ROOT / "tests" / "fixtures" / "ve07-summary-failing.json"
NS = uuid.uuid5(uuid.NAMESPACE_URL, "https://github.com/samyoon727ca/uas-sec-oscal")
RUN = "VE-07/38345035945/1"
DRAFT = "\n\nDRAFT: this mapping row is `proposed`, not approved by the owner."

# Intentional differences between the generated file and the hand-written golden
# file. test_generated_matches_the_golden_file checks each one and undoes it; what
# is left must equal the golden file exactly.
INTENTIONAL_DIFFERENCES = (
    "metadata.title names every control mappings/controls.yaml maps to SR-005 "
    "(SI-7, SI-7(9) and SI-7(15)) and ends in ' (DRAFT)' while the mapping is not approved",
    "metadata.remarks says the file is generated rather than hand-written",
    "import-ap.href is ../handwritten/ve07-assessment-plan.json, because the generated file is in oscal/generated/",
    "reviewed-controls also lists si-7.9 and si-7.15",
    "there is one finding per mapped control: si-7.9 and si-7.15 get findings like the si-7 one",
    "each finding has a mapping-status prop with its mapping row's status",
    "findings from unapproved mapping rows end with a DRAFT paragraph",
)


def uuid5(name):
    return str(uuid.uuid5(NS, name))


def _props(obj):
    out = {}
    for prop in obj["props"]:
        assert prop["ns"] == UAS_NS
        out[prop["name"]] = prop["value"]
    return out


def _build(summary_path=DEFAULT_SUMMARY, mapping=None, summary=None):
    loaded, sha = load_summary(summary_path)
    return build_assessment_results(
        summary if summary is not None else loaded,
        sha,
        mapping or load_mapping(),
        load_requirements(),
        "VE-07",
        summary_href="summary.json",
        plan_href="plan.json",
    )["assessment-results"]


def _approved_si7_only():
    mapping = load_mapping()
    mapping["approved_by"] = "owner"
    mapping["mappings"] = [row for row in mapping["mappings"] if row["requirement_id"] == "SR-005"]
    mapping["mappings"][0].update(controls=["si-7"], status="approved")
    return mapping


# Golden equivalence


def test_generated_matches_the_golden_file():
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))["assessment-results"]
    gen = json.loads(GENERATED.read_text(encoding="utf-8"))["assessment-results"]

    # metadata.title
    assert gen["metadata"]["title"] == (
        golden["metadata"]["title"].replace("against SI-7 ", "against SI-7, SI-7(9) and SI-7(15) ") + " (DRAFT)"
    )
    gen["metadata"]["title"] = golden["metadata"]["title"]
    # metadata.remarks
    assert gen["metadata"]["remarks"].startswith("Generated by `uas-oscal results`")
    gen["metadata"]["remarks"] = golden["metadata"]["remarks"]
    # import-ap.href
    assert (GENERATED.parent / gen["import-ap"]["href"]).resolve() == PLAN
    gen["import-ap"]["href"] = golden["import-ap"]["href"]

    (result,) = gen["results"]
    # reviewed-controls
    (selection,) = result["reviewed-controls"]["control-selections"]
    assert [c["control-id"] for c in selection["include-controls"]] == ["si-7", "si-7.9", "si-7.15"]
    selection["include-controls"] = [{"control-id": "si-7"}]
    # findings for the extra controls
    findings = result["findings"]
    assert [f["target"]["target-id"] for f in findings] == ["si-7_obj", "si-7.9_obj", "si-7.15_obj"]
    si7 = findings[0]
    for finding, control in zip(findings[1:], ["si-7.9", "si-7.15"], strict=True):
        assert finding["uuid"] == uuid5(f"finding/{RUN}/SR-005/{control}")
        assert finding["title"] == f"SR-005 against {control_title(control)}: satisfied"
        assert finding["target"]["status"] == si7["target"]["status"]
        assert finding["related-observations"] == si7["related-observations"]
        assert finding["description"] == si7["description"].replace("SI-7 objective", f"{control_title(control)} objective")
        assert finding["props"] == si7["props"]
    result["findings"] = [si7]
    # mapping-status prop
    assert si7["props"][1] == {"name": "mapping-status", "ns": UAS_NS, "value": "proposed"}
    del si7["props"][1]
    # DRAFT paragraph
    assert si7["description"].endswith(DRAFT)
    si7["description"] = si7["description"][: -len(DRAFT)]

    assert gen == golden


def test_approved_si7_only_mapping_differs_from_golden_only_in_provenance():
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))["assessment-results"]
    gen = _build(mapping=_approved_si7_only())
    gen["metadata"]["remarks"] = golden["metadata"]["remarks"]
    gen["import-ap"]["href"] = golden["import-ap"]["href"]
    (finding,) = gen["results"][0]["findings"]
    assert finding["props"].pop() == {"name": "mapping-status", "ns": UAS_NS, "value": "approved"}
    for obs in gen["results"][0]["observations"]:
        assert obs["relevant-evidence"][0]["href"] == "summary.json"
        obs["relevant-evidence"][0]["href"] = golden["results"][0]["observations"][0]["relevant-evidence"][0]["href"]
    assert gen == golden


# Determinism


def test_committed_file_is_up_to_date():
    assert generate(DEFAULT_SUMMARY, GENERATED, "VE-07") == GENERATED.read_text(encoding="utf-8")


def test_cli_twice_is_byte_identical(tmp_path):
    outputs = []
    for name in ("a.json", "b.json"):
        out = tmp_path / name
        argv = ["results", "--summary", str(DEFAULT_SUMMARY), "--mapping", str(DEFAULT_MAPPING), "--ve", "VE-07"]
        assert main([*argv, "-o", str(out)]) == 0
        outputs.append(out.read_bytes())
    assert outputs[0] == outputs[1]
    assert b"\r\n" not in outputs[0]


def test_output_has_sorted_keys():
    text = generate(DEFAULT_SUMMARY, GENERATED, "VE-07")
    assert text == json.dumps(json.loads(text), indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def test_hrefs_are_relative_to_the_output(tmp_path):
    out = tmp_path / "deep" / "er" / "ar.json"
    assert main(["results", "--summary", str(DEFAULT_SUMMARY), "--ve", "VE-07", "-o", str(out)]) == 0
    doc = json.loads(out.read_text(encoding="utf-8"))["assessment-results"]
    assert (out.parent / doc["import-ap"]["href"]).resolve() == PLAN
    for obs in doc["results"][0]["observations"]:
        assert (out.parent / obs["relevant-evidence"][0]["href"]).resolve() == DEFAULT_SUMMARY


def test_uuids_are_unique():
    seen = set()

    def collect(node):
        if isinstance(node, dict):
            if "uuid" in node:
                assert node["uuid"] not in seen
                seen.add(node["uuid"])
            for value in node.values():
                collect(value)
        elif isinstance(node, list):
            for value in node:
                collect(value)

    collect(json.loads(GENERATED.read_text(encoding="utf-8")))
    assert len(seen) == 1 + 1 + 5 + 3


# Finding status


def test_failing_test_case_fixture_is_not_satisfied():
    ar = _build(FAILING)
    (result,) = ar["results"]
    run = "VE-07/38345099999/2"
    assert ar["uuid"] == uuid5(f"assessment-results/{run}")
    assert [_props(o)["test-outcome"] for o in result["observations"]] == ["passed", "failed"]
    tc03 = result["observations"][1]
    assert tc03["title"] == "VE-07 TC-03: failed"
    assert "- TC-03b (test): Initramfs changed after signing. ok: false" in tc03["description"]
    assert [f["target"]["target-id"] for f in result["findings"]] == ["si-7_obj", "si-7.9_obj", "si-7.15_obj"]
    for finding in result["findings"]:
        assert finding["target"]["status"]["state"] == "not-satisfied"
        assert finding["title"].endswith(": not-satisfied")
        assert "reports `passed: false`, and these test cases are not `passed`: TC-03 (`failed`)." in (
            finding["description"]
        )
        assert "objective is therefore `not-satisfied` for SR-005" in finding["description"]


@pytest.mark.parametrize(
    ("passed", "outcome", "state"),
    [(True, "passed", "satisfied"), (False, "passed", "not-satisfied"), (True, "skipped", "not-satisfied")],
)
def test_satisfied_needs_passed_and_every_test_case_passed(passed, outcome, state):
    summary, _ = load_summary(DEFAULT_SUMMARY)
    summary["passed"] = passed
    summary["test_cases"]["TC-05"] = outcome
    for finding in _build(summary=summary)["results"][0]["findings"]:
        assert finding["target"]["status"]["state"] == state


# Approval gate


def test_proposed_rows_are_marked_draft():
    ar = _build()
    assert ar["metadata"]["title"].endswith(" (DRAFT)")
    for finding in ar["results"][0]["findings"]:
        assert _props(finding) == {"requirement-id": "SR-005", "mapping-status": "proposed"}
        assert finding["description"].endswith(DRAFT)


def test_approved_mapping_is_not_draft():
    mapping = load_mapping()
    mapping["approved_by"] = "owner"
    for row in mapping["mappings"]:
        row["status"] = "approved"
    ar = _build(mapping=mapping)
    assert "DRAFT" not in ar["metadata"]["title"]
    for finding in ar["results"][0]["findings"]:
        assert _props(finding)["mapping-status"] == "approved"
        assert "DRAFT" not in finding["description"]


def test_approved_row_without_approved_by_keeps_the_document_draft():
    mapping = load_mapping()
    for row in mapping["mappings"]:
        row["status"] = "approved"
    ar = _build(mapping=mapping)
    assert ar["metadata"]["title"].endswith(" (DRAFT)")
    assert all("DRAFT" not in f["description"] for f in ar["results"][0]["findings"])


# Malformed inputs


def _summary_with(change):
    summary = json.loads(FAILING.read_text(encoding="utf-8"))
    change(summary)
    return summary


@pytest.mark.parametrize(
    ("change", "message"),
    [
        (lambda s: s.update(surprise=1), "summary: unknown field(s) surprise"),
        (lambda s: s.pop("passed"), "summary: missing field(s) passed"),
        (lambda s: s["environment"].pop("run_id"), "environment: missing field(s) run_id"),
        (lambda s: s["environment"].update(new_key="x"), "environment: unknown field(s) new_key"),
        (lambda s: s["git"].update(branch="x"), "git: unknown field(s) branch"),
        (lambda s: s["runs"][0].update(verdict="x"), "runs[0]: unknown field(s) verdict"),
        (lambda s: s["runs"][1].pop("ok"), "runs[1]: missing field(s) ok"),
        (lambda s: s.update(passed="true"), "summary.passed must be true or false"),
        (lambda s: s.update(date_utc="2026-10-14"), "summary.date_utc"),
        (lambda s: s.update(test_cases={}), "test_cases must be a non-empty object"),
        (lambda s: s["test_cases"].update({"TC-09": "passed"}), "test_cases.TC-09: no runs recorded"),
        (lambda s: s["runs"][0].update(tc="TC-02"), "runs[0] (TC-01): test case TC-02 is not in test_cases"),
        (lambda s: s["git"].update(commit="2" * 40), "differs from environment.sha"),
        (lambda s: s["environment"].update(run_url="https://example.com/run/1"), "environment.run_url must be"),
        (lambda s: s["environment"].update(run_id="1"), "run_url names run 38345099999, but run_id is 1"),
        (lambda s: s["runs"][0].update(title=""), "runs[0].title must be a non-empty string"),
        (lambda s: s.update(event="VE-08"), "summary.json is for VE-08, not VE-07"),
    ],
)
def test_malformed_summary_is_a_clean_cli_error(tmp_path, capsys, change, message):
    bad = tmp_path / "summary.json"
    bad.write_text(json.dumps(_summary_with(change)), encoding="utf-8")
    out = tmp_path / "ar.json"
    assert main(["results", "--summary", str(bad), "--ve", "VE-07", "-o", str(out)]) == 1
    err = capsys.readouterr().err
    assert err.startswith("uas-oscal results: ")
    assert message in err
    assert not out.exists()


def test_invalid_json_is_a_clean_cli_error(tmp_path, capsys):
    bad = tmp_path / "summary.json"
    bad.write_text("{", encoding="utf-8")
    out = tmp_path / "ar.json"
    assert main(["results", "--summary", str(bad), "--ve", "VE-07", "-o", str(out)]) == 1
    assert f"uas-oscal results: {bad}: invalid JSON" in capsys.readouterr().err
    assert not out.exists()


def test_unsupported_verification_event():
    with pytest.raises(ValueError, match="unsupported verification event VE-08"):
        generate(DEFAULT_SUMMARY, GENERATED, "VE-08")
    with pytest.raises(SystemExit):
        main(["results", "--summary", str(DEFAULT_SUMMARY), "--ve", "VE-08", "-o", "x.json"])

